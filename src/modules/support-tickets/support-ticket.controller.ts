import {
  Body,
  Controller,
  Get,
  Param,
  ParseUUIDPipe,
  Patch,
  Post,
  Query,
  UseGuards,
} from '@nestjs/common';
import {
  ApiBearerAuth,
  ApiCreatedResponse,
  ApiForbiddenResponse,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';

import { SupportTicketService } from './support-ticket.service';
import { CreateSupportTicketDto } from './dto/create-support-ticket.dto';
import { QueryMyTicketsDto } from './dto/query-my-tickets.dto';

import { RequirePermissions } from '../auth/decorators/permissions.decorator';
import { PermissionsGuard } from '../auth/guards/permissions.guard';
import { CurrentUser } from '../auth/decorators/current-user.decorator';
import { PERMISSION } from '../../rbac/rbac.constants';
import { TenantContextService } from '../../core/tenant-context/tenant-context.service';
import { ActiveTenantGuard } from '../../core/tenant-context/active-tenant.guard';
import type { AuthenticatedUser } from '../auth/interfaces/authenticated-user.interface';

const S_ERROR = {
  type: 'object',
  properties: {
    statusCode: { type: 'number' },
    errorCode: { type: 'string' },
    message: { type: 'string' },
    requestId: { type: 'string', format: 'uuid' },
    timestamp: { type: 'string', format: 'date-time' },
  },
};

/**
 * Tenant-side Support Tickets. Guarded by PermissionsGuard + ActiveTenantGuard;
 * tenant id always from TenantContext, never request input. Deliberately NOT
 * gated by `@RequireActiveSubscription()` — a tenant whose subscription has
 * lapsed still needs to be able to reach support.
 */
@ApiTags('Support Tickets')
@ApiBearerAuth('JWT-auth')
@Controller('support-tickets')
@UseGuards(PermissionsGuard, ActiveTenantGuard)
export class SupportTicketController {
  constructor(
    private readonly ticketsService: SupportTicketService,
    private readonly ctx: TenantContextService,
  ) {}

  @ApiOperation({
    summary: 'Create a support ticket',
    description:
      '**Protected — `support_tickets.create`. Clinic active.** Ticket number is generated by the backend; status always starts at `open`; tenant is always the caller\'s tenant.',
  })
  @ApiCreatedResponse({ description: 'Ticket created.' })
  @ApiUnauthorizedResponse({ description: 'Missing or invalid access token.', schema: S_ERROR })
  @ApiForbiddenResponse({ description: 'Caller lacks `support_tickets.create`, or clinic inactive.', schema: S_ERROR })
  @Post()
  @RequirePermissions(PERMISSION.SUPPORT_TICKETS_CREATE)
  create(@Body() dto: CreateSupportTicketDto, @CurrentUser() user: AuthenticatedUser) {
    return this.ticketsService.create(
      this.ctx.requireTenantId(),
      { id: user.id, email: user.email },
      dto,
    );
  }

  @ApiOperation({
    summary: 'List my tenant\'s support tickets',
    description: '**Protected — `support_tickets.read`. Clinic active.** Tenant-scoped, filterable + paginated.',
  })
  @ApiOkResponse({ description: 'Paginated tickets.' })
  @ApiUnauthorizedResponse({ description: 'Missing or invalid access token.', schema: S_ERROR })
  @ApiForbiddenResponse({ description: 'Caller lacks `support_tickets.read`, or clinic inactive.', schema: S_ERROR })
  @Get()
  @RequirePermissions(PERMISSION.SUPPORT_TICKETS_READ)
  list(@Query() query: QueryMyTicketsDto) {
    return this.ticketsService.listForTenant(this.ctx.requireTenantId(), query);
  }

  @ApiOperation({
    summary: 'Get a support ticket',
    description: '**Protected — `support_tickets.read`. Clinic active.** Includes tenant-visible status history. Another tenant\'s ticket returns 404. Internal admin notes are never included.',
  })
  @ApiParam({ name: 'id', description: 'Ticket UUID', type: 'string', format: 'uuid' })
  @ApiOkResponse({ description: 'Ticket details.' })
  @ApiUnauthorizedResponse({ description: 'Missing or invalid access token.', schema: S_ERROR })
  @ApiForbiddenResponse({ description: 'Caller lacks `support_tickets.read`, or clinic inactive.', schema: S_ERROR })
  @ApiNotFoundResponse({ description: 'Ticket not found in this tenant.', schema: S_ERROR })
  @Get(':id')
  @RequirePermissions(PERMISSION.SUPPORT_TICKETS_READ)
  get(@Param('id', ParseUUIDPipe) id: string) {
    return this.ticketsService.getForTenant(this.ctx.requireTenantId(), id);
  }

  @ApiOperation({
    summary: "Confirm resolution and close the clinic's own ticket",
    description:
      '**Protected — `support_tickets.close`. Clinic active.** Only valid from `resolved` — a clinic can never resolve a ticket or close one that isn\'t resolved yet, and can never close another tenant\'s ticket. `closedAt` is always backend-generated.',
  })
  @ApiParam({ name: 'id', description: 'Ticket UUID', type: 'string', format: 'uuid' })
  @ApiOkResponse({ description: 'Ticket closed.' })
  @ApiUnauthorizedResponse({ description: 'Missing or invalid access token.', schema: S_ERROR })
  @ApiForbiddenResponse({ description: 'Caller lacks `support_tickets.close`, or clinic inactive.', schema: S_ERROR })
  @ApiNotFoundResponse({ description: 'Ticket not found in this tenant.', schema: S_ERROR })
  @Patch(':id/close')
  @RequirePermissions(PERMISSION.SUPPORT_TICKETS_CLOSE)
  close(@Param('id', ParseUUIDPipe) id: string, @CurrentUser() user: AuthenticatedUser) {
    return this.ticketsService.closeOwnTicket(
      this.ctx.requireTenantId(),
      { id: user.id, email: user.email, role: 'clinic' },
      id,
    );
  }
}
