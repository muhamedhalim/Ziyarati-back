import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { DataSource } from 'typeorm';

import { QueueService } from '../../queue/queue.service';
import { QUEUE } from '../../queue/queue.constants';
import { currentPeriodMonth } from '../ai/ai.constants';

const n = (v: unknown): number => {
  const x = Number(v);
  return Number.isFinite(x) ? x : 0;
};

/**
 * Super-admin AI monitoring (Feature 10). Read-only, CROSS-TENANT aggregation over
 * the EXISTING AI stores — `ai_usage_logs` (requests/tokens), `ai_cost_logs`
 * (in/out tokens + spend), `ai_conversations` (counts/status/channel/active),
 * `ai_messages`, `handover_requests` — plus the AI BullMQ queue depth (reuses
 * `QueueService`). It computes NOTHING that the per-tenant `AiAnalyticsService`
 * already computes for a single tenant; this is the platform-wide lens.
 *
 * Honesty: latency, streaming duration, per-model usage, embedding tokens, and
 * "revenue generated by AI" are NOT persisted in the current schema, so they are
 * reported under `notTracked` rather than fabricated.
 */
@Injectable()
export class AiMonitoringService {
  constructor(
    private readonly dataSource: DataSource,
    private readonly queues: QueueService,
    private readonly config: ConfigService,
  ) {}

  async overview() {
    const period = currentPeriodMonth();

    const [usage] = await this.dataSource.query(
      `SELECT COALESCE(SUM(total_requests),0)::bigint AS requests,
              COALESCE(SUM(total_tokens),0)::bigint AS tokens,
              COALESCE(SUM(total_requests) FILTER (WHERE period_month = $1),0)::bigint AS requests_period,
              COALESCE(SUM(total_tokens) FILTER (WHERE period_month = $1),0)::bigint AS tokens_period
         FROM ai_usage_logs`,
      [period],
    );
    const [cost] = await this.dataSource.query(
      `SELECT COALESCE(SUM(input_tokens),0)::bigint AS input,
              COALESCE(SUM(output_tokens),0)::bigint AS output,
              COALESCE(SUM(total_cost_usd),0) AS cost,
              COALESCE(SUM(total_cost_usd) FILTER (WHERE period_month = $1),0) AS cost_period
         FROM ai_cost_logs`,
      [period],
    );

    const convByStatus = await this.dataSource.query(
      `SELECT status, COUNT(*)::int AS count FROM ai_conversations GROUP BY status`,
    );
    const convByChannel = await this.dataSource.query(
      `SELECT channel, COUNT(*)::int AS count FROM ai_conversations GROUP BY channel`,
    );
    const [msg] = await this.dataSource.query(`SELECT COUNT(*)::int AS c FROM ai_messages`);
    const [handover] = await this.dataSource.query(
      `SELECT COUNT(*)::int AS total,
              COUNT(*) FILTER (WHERE status = 'RESOLVED')::int AS resolved
         FROM handover_requests`,
    );

    const byStatus: Record<string, number> = {};
    let totalConversations = 0;
    for (const r of convByStatus) {
      byStatus[r.status ?? 'UNKNOWN'] = n(r.count);
      totalConversations += n(r.count);
    }
    const activeSessions = byStatus['ACTIVE'] ?? 0;

    const topByTokens = await this.dataSource.query(
      `SELECT t.id, t.name, COALESCE(SUM(u.total_tokens),0)::bigint AS tokens, COALESCE(SUM(u.total_requests),0)::bigint AS requests
         FROM ai_usage_logs u JOIN tenants t ON t.id = u."tenantId" AND t.deleted_at IS NULL
        GROUP BY t.id, t.name ORDER BY tokens DESC LIMIT 10`,
    );
    const topByCost = await this.dataSource.query(
      `SELECT t.id, t.name, COALESCE(SUM(c.total_cost_usd),0) AS cost
         FROM ai_cost_logs c JOIN tenants t ON t.id = c."tenantId" AND t.deleted_at IS NULL
        GROUP BY t.id, t.name ORDER BY cost DESC LIMIT 10`,
    );

    const queueCounts = await this.queues.queueCounts().catch(() => ({}));
    const aiQueue = queueCounts[QUEUE.AI] ?? {};

    const totalRequests = n(usage?.requests);
    const handoverTotal = n(handover?.total);

    return {
      periodMonth: period,
      requests: {
        total: totalRequests,
        thisPeriod: n(usage?.requests_period),
      },
      tokens: {
        total: n(usage?.tokens),
        thisPeriod: n(usage?.tokens_period),
        promptTokens: n(cost?.input),
        completionTokens: n(cost?.output),
      },
      cost: {
        totalUsd: +n(cost?.cost).toFixed(6),
        thisPeriodUsd: +n(cost?.cost_period).toFixed(6),
      },
      conversations: {
        total: totalConversations,
        byStatus,
        byChannel: convByChannel.map((r: Record<string, unknown>) => ({ channel: r.channel as string, count: n(r.count) })),
        activeSessions,
        totalMessages: n(msg?.c),
        avgMessagesPerConversation: totalConversations ? +(n(msg?.c) / totalConversations).toFixed(2) : 0,
      },
      handover: {
        total: handoverTotal,
        resolved: n(handover?.resolved),
        handoverRatePct: totalConversations ? +((handoverTotal / totalConversations) * 100).toFixed(2) : 0,
      },
      queue: {
        waiting: n(aiQueue.waiting),
        active: n(aiQueue.active),
        delayed: n(aiQueue.delayed),
        completed: n(aiQueue.completed),
        failed: n(aiQueue.failed),
      },
      providers: [
        { name: 'OpenAI', configured: !!this.config.get<string>('OPENAI_API_KEY') },
        { name: 'Anthropic', configured: !!this.config.get<string>('ANTHROPIC_API_KEY') },
        { name: 'Azure OpenAI', configured: !!this.config.get<string>('AZURE_OPENAI_API_KEY') },
      ],
      topTenantsByTokens: topByTokens.map((r: Record<string, unknown>) => ({
        tenantId: r.id as string, tenantName: r.name as string, tokens: n(r.tokens), requests: n(r.requests),
      })),
      topTenantsByCost: topByCost.map((r: Record<string, unknown>) => ({
        tenantId: r.id as string, tenantName: r.name as string, costUsd: +n(r.cost).toFixed(6),
      })),
      notTracked: [
        'latency', 'streamingDuration', 'perModelUsage', 'embeddingTokens',
        'toolExecutionTime', 'bookingsCreatedByAi', 'revenueGeneratedByAi',
      ],
      collectedAt: new Date().toISOString(),
    };
  }
}
