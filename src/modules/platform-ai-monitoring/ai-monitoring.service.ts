import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { DataSource } from 'typeorm';

import { QueueService } from '../../queue/queue.service';
import { QUEUE } from '../../queue/queue.constants';
import { currentPeriodMonth } from '../ai/ai.constants';

const n = (v: unknown): number => {
  const x = Number(v);
  return Number.isFinite(x) ? x : 0;
};

/**
 * Super-admin AI monitoring (Feature 10). Read-only, CROSS-TENANT aggregation over
 * the EXISTING AI stores — `ai_usage_logs` (requests/tokens), `ai_cost_logs`
 * (in/out tokens + spend), `ai_conversations` (counts/status/channel/active),
 * `ai_messages`, `handover_requests`, `ai_execution_metrics` (latency/tool/error —
 * Advanced AI Monitoring) — plus the AI BullMQ queue depth (reuses
 * `QueueService`). It computes NOTHING that the per-tenant `AiAnalyticsService`/
 * `AiMetricsService` already computes for a single tenant; this is the
 * platform-wide lens over the SAME tables (no duplicate capture).
 *
 * Honesty: "bookings created by AI" and "revenue generated by AI" have no
 * attribution column anywhere in the schema, so they remain in `notTracked`.
 */
@Injectable()
export class AiMonitoringService {
  constructor(
    private readonly dataSource: DataSource,
    private readonly queues: QueueService,
    private readonly config: ConfigService,
  ) {}

  async overview() {
    const period = currentPeriodMonth();

    const [usage] = await this.dataSource.query(
      `SELECT COALESCE(SUM(total_requests),0)::bigint AS requests,
              COALESCE(SUM(total_tokens),0)::bigint AS tokens,
              COALESCE(SUM(total_requests) FILTER (WHERE period_month = $1),0)::bigint AS requests_period,
              COALESCE(SUM(total_tokens) FILTER (WHERE period_month = $1),0)::bigint AS tokens_period
         FROM ai_usage_logs`,
      [period],
    );
    const [cost] = await this.dataSource.query(
      `SELECT COALESCE(SUM(input_tokens),0)::bigint AS input,
              COALESCE(SUM(output_tokens),0)::bigint AS output,
              COALESCE(SUM(total_cost_usd),0) AS cost,
              COALESCE(SUM(total_cost_usd) FILTER (WHERE period_month = $1),0) AS cost_period
         FROM ai_cost_logs`,
      [period],
    );

    const convByStatus = await this.dataSource.query(
      `SELECT status, COUNT(*)::int AS count FROM ai_conversations GROUP BY status`,
    );
    const convByChannel = await this.dataSource.query(
      `SELECT channel, COUNT(*)::int AS count FROM ai_conversations GROUP BY channel`,
    );
    const [msg] = await this.dataSource.query(`SELECT COUNT(*)::int AS c FROM ai_messages`);
    const [handover] = await this.dataSource.query(
      `SELECT COUNT(*)::int AS total,
              COUNT(*) FILTER (WHERE status = 'RESOLVED')::int AS resolved
         FROM handover_requests`,
    );

    const byStatus: Record<string, number> = {};
    let totalConversations = 0;
    for (const r of convByStatus) {
      byStatus[r.status ?? 'UNKNOWN'] = n(r.count);
      totalConversations += n(r.count);
    }
    const activeSessions = byStatus['ACTIVE'] ?? 0;

    const topByTokens = await this.dataSource.query(
      `SELECT t.id, t.name, COALESCE(SUM(u.total_tokens),0)::bigint AS tokens, COALESCE(SUM(u.total_requests),0)::bigint AS requests
         FROM ai_usage_logs u JOIN tenants t ON t.id = u."tenantId" AND t.deleted_at IS NULL
        GROUP BY t.id, t.name ORDER BY tokens DESC LIMIT 10`,
    );
    const topByCost = await this.dataSource.query(
      `SELECT t.id, t.name, COALESCE(SUM(c.total_cost_usd),0) AS cost
         FROM ai_cost_logs c JOIN tenants t ON t.id = c."tenantId" AND t.deleted_at IS NULL
        GROUP BY t.id, t.name ORDER BY cost DESC LIMIT 10`,
    );

    const queueCounts = await this.queues.queueCounts().catch(() => ({}));
    const aiQueue = queueCounts[QUEUE.AI] ?? {};
    const queueTiming = await this.aiQueueTiming();

    const [execAgg] = await this.dataSource.query(
      `SELECT
         count(*)::int AS n,
         count(*) FILTER (WHERE success = false)::int AS error_count,
         COALESCE(avg(total_latency_ms), 0) AS avg_latency_ms,
         COALESCE(percentile_cont(0.5) WITHIN GROUP (ORDER BY total_latency_ms), 0) AS p50_latency_ms,
         COALESCE(percentile_cont(0.95) WITHIN GROUP (ORDER BY total_latency_ms), 0) AS p95_latency_ms,
         COALESCE(percentile_cont(0.99) WITHIN GROUP (ORDER BY total_latency_ms), 0) AS p99_latency_ms,
         COALESCE(avg(first_token_ms) FILTER (WHERE first_token_ms IS NOT NULL), 0) AS avg_first_token_ms,
         COALESCE(avg(streaming_duration_ms) FILTER (WHERE streaming_duration_ms IS NOT NULL), 0) AS avg_streaming_duration_ms,
         COALESCE(sum(tool_calls_count), 0)::int AS tool_calls,
         COALESCE(sum(tool_success_count), 0)::int AS tool_success,
         COALESCE(sum(tool_failure_count), 0)::int AS tool_failure,
         COALESCE(sum(completion_tokens), 0)::bigint AS completion_tokens,
         COALESCE(sum(total_latency_ms), 0)::bigint AS total_latency_ms_sum
       FROM ai_execution_metrics`,
    );
    const costByModel = await this.dataSource.query(
      `SELECT model, count(*)::int AS requests, COALESCE(sum(total_tokens),0)::bigint AS tokens, COALESCE(sum(cost_usd),0) AS cost_usd
         FROM ai_execution_metrics GROUP BY model ORDER BY cost_usd DESC LIMIT 10`,
    );
    const costPerTenant = await this.dataSource.query(
      `SELECT t.id, t.name, COALESCE(sum(m.cost_usd),0) AS cost_usd, count(*)::int AS requests
         FROM ai_execution_metrics m JOIN tenants t ON t.id = m."tenantId" AND t.deleted_at IS NULL
        GROUP BY t.id, t.name ORDER BY cost_usd DESC LIMIT 10`,
    );

    const execRequests = n(execAgg?.n);
    const execCompletionTokens = n(execAgg?.completion_tokens);
    const execLatencySumSec = n(execAgg?.total_latency_ms_sum) / 1000;

    const totalRequests = n(usage?.requests);
    const handoverTotal = n(handover?.total);

    return {
      periodMonth: period,
      requests: {
        total: totalRequests,
        thisPeriod: n(usage?.requests_period),
      },
      tokens: {
        total: n(usage?.tokens),
        thisPeriod: n(usage?.tokens_period),
        promptTokens: n(cost?.input),
        completionTokens: n(cost?.output),
      },
      cost: {
        totalUsd: +n(cost?.cost).toFixed(6),
        thisPeriodUsd: +n(cost?.cost_period).toFixed(6),
      },
      conversations: {
        total: totalConversations,
        byStatus,
        byChannel: convByChannel.map((r: Record<string, unknown>) => ({ channel: r.channel as string, count: n(r.count) })),
        activeSessions,
        totalMessages: n(msg?.c),
        avgMessagesPerConversation: totalConversations ? +(n(msg?.c) / totalConversations).toFixed(2) : 0,
      },
      handover: {
        total: handoverTotal,
        resolved: n(handover?.resolved),
        handoverRatePct: totalConversations ? +((handoverTotal / totalConversations) * 100).toFixed(2) : 0,
      },
      queue: {
        waiting: n(aiQueue.waiting),
        active: n(aiQueue.active),
        delayed: n(aiQueue.delayed),
        completed: n(aiQueue.completed),
        failed: n(aiQueue.failed),
        avgWaitMs: queueTiming.avgWaitMs,
        avgProcessingMs: queueTiming.avgProcessingMs,
        sampledJobs: queueTiming.sampled,
      },
      providers: [
        { name: 'OpenAI', configured: !!this.config.get<string>('OPENAI_API_KEY') },
        { name: 'Anthropic', configured: !!this.config.get<string>('ANTHROPIC_API_KEY') },
        { name: 'Azure OpenAI', configured: !!this.config.get<string>('AZURE_OPENAI_API_KEY') },
      ],
      topTenantsByTokens: topByTokens.map((r: Record<string, unknown>) => ({
        tenantId: r.id as string, tenantName: r.name as string, tokens: n(r.tokens), requests: n(r.requests),
      })),
      topTenantsByCost: topByCost.map((r: Record<string, unknown>) => ({
        tenantId: r.id as string, tenantName: r.name as string, costUsd: +n(r.cost).toFixed(6),
      })),
      // Advanced AI Monitoring (Feature 6) — real numbers from ai_execution_metrics,
      // captured by AiExecutionService on every turn across every tenant.
      performance: {
        requests: execRequests,
        errorRate: execRequests > 0 ? n(execAgg?.error_count) / execRequests : 0,
        latencyMs: {
          avg: n(execAgg?.avg_latency_ms),
          p50: n(execAgg?.p50_latency_ms),
          p95: n(execAgg?.p95_latency_ms),
          p99: n(execAgg?.p99_latency_ms),
        },
        avgFirstTokenMs: n(execAgg?.avg_first_token_ms),
        avgStreamingDurationMs: n(execAgg?.avg_streaming_duration_ms),
        tokensPerSecond: execLatencySumSec > 0 ? +(execCompletionTokens / execLatencySumSec).toFixed(2) : 0,
        tools: {
          calls: n(execAgg?.tool_calls),
          succeeded: n(execAgg?.tool_success),
          failed: n(execAgg?.tool_failure),
          successRate: n(execAgg?.tool_calls) > 0 ? n(execAgg?.tool_success) / n(execAgg?.tool_calls) : null,
        },
        costByModel: costByModel.map((r: Record<string, unknown>) => ({
          model: r.model as string, requests: n(r.requests), tokens: n(r.tokens), costUsd: +n(r.cost_usd).toFixed(6),
        })),
        costPerTenant: costPerTenant.map((r: Record<string, unknown>) => ({
          tenantId: r.id as string, tenantName: r.name as string, costUsd: +n(r.cost_usd).toFixed(6), requests: n(r.requests),
        })),
      },
      notTracked: ['bookingsCreatedByAi', 'revenueGeneratedByAi'],
      collectedAt: new Date().toISOString(),
    };
  }

  /**
   * Samples recent completed/failed jobs on the AI queue to derive REAL average
   * wait (enqueue → start) and processing (start → finish) durations from BullMQ
   * job timestamps — `QueueService.queue()` is the existing accessor, no new
   * queue plumbing. Falls back to zeros when the queue has no recent history.
   */
  private async aiQueueTiming(): Promise<{ avgWaitMs: number; avgProcessingMs: number; sampled: number }> {
    try {
      const queue = this.queues.queue(QUEUE.AI);
      const jobs = await queue.getJobs(['completed', 'failed'], 0, 49, true);
      let waitSum = 0;
      let procSum = 0;
      let counted = 0;
      for (const job of jobs) {
        if (job.processedOn && job.timestamp) waitSum += job.processedOn - job.timestamp;
        if (job.finishedOn && job.processedOn) procSum += job.finishedOn - job.processedOn;
        if (job.processedOn) counted += 1;
      }
      return {
        avgWaitMs: counted > 0 ? Math.round(waitSum / counted) : 0,
        avgProcessingMs: counted > 0 ? Math.round(procSum / counted) : 0,
        sampled: counted,
      };
    } catch {
      return { avgWaitMs: 0, avgProcessingMs: 0, sampled: 0 };
    }
  }
}
