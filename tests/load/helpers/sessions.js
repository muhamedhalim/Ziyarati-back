/**
 * Campaign session + data-pack loader (the 20K-VU counterpart of auth.js's
 * buildSessions()).
 *
 * WHY NOT LOG IN PER VU. 20,000 VUs x bcrypt-12 would turn every scenario into
 * a login benchmark and make setup() impossible. Access tokens are stateless
 * (JwtStrategy verifies signature + expiry, then re-reads the user), so
 * lab/mint-sessions.mjs signs them offline with the LAB's own JWT secret and
 * writes sessions.json. The real guard chain still runs on every request:
 * signature, expiry, the 6-table principal join, permissions, CSRF
 * double-submit, tenant/feature/subscription gates. What is NOT exercised is
 * login/bcrypt — that is what auth-herd and a small real-login share of
 * business-mix are for, and every report states it.
 *
 * Files (all gitignored, generated by lab/mint-sessions.mjs, mounted at
 * /scripts/data/generated):
 *   sessions.json   { meta, index:{byRole,hot,...}, sessions:[session...] }
 *   pack-<name>.json  JSON array (queue, payments, partner, marketplace, wa, auth)
 *
 * SharedArray keeps ONE copy in memory for all VUs; elements are parsed on
 * access, so callers cache the object they pick (see pickSession).
 */
import { SharedArray } from 'k6/data';

const DIR = __ENV.LT_DATA_DIR || '/scripts/data/generated';

// A missing sessions.json yields an EMPTY pool instead of an init error, so scenarios that
// need no sessions (calibrate, auth-herd, public-api) still load; scenarios that DO need
// them fail fast in campaignSetup() with a clear message.
const EMPTY_INDEX = { count: 0, tenantCount: 0, byRole: {}, hotByRole: {}, ownerByTenant: {} };
function readDoc() {
  try { return JSON.parse(open(`${DIR}/sessions.json`)); } catch (e) { return { sessions: [], index: EMPTY_INDEX }; }
}

export const sessionsArr = new SharedArray('lt-sessions', () => readDoc().sessions);

const indexArr = new SharedArray('lt-session-index', () => [readDoc().index]);

let _index = null;
export function sessionIndex() {
  if (!_index) _index = indexArr[0];
  return _index;
}

const packs = {};
/** Optional data pack; a missing file yields an EMPTY array so flows can skip. */
export function pack(name) {
  if (!packs[name]) {
    packs[name] = new SharedArray(`lt-pack-${name}`, () => {
      try {
        return JSON.parse(open(`${DIR}/pack-${name}.json`));
      } catch (e) {
        return [];
      }
    });
  }
  return packs[name];
}

/** Deterministic 0..99 bucket of a VU id (stable across iterations and runs). */
export function bucketOf(vu) {
  return ((vu * 2654435761) >>> 0) % 100;
}

// Every flow derives booking slots from (VU, iteration, runSeed). The runner passes ONE LT_RUN_SEED to
// every generator so contention modes still collide on purpose, but two runs on the same database
// never reuse the same slots (a repeat run would otherwise book into last run's occupied slots).
const RUN_SEED = Number(__ENV.LT_RUN_SEED) || (Math.floor(Date.now() / 60000) % 100000);

let _mine = null;
/**
 * The VU's session for a persona's role set. Chosen once per VU and cached.
 * `hotShare` (0..1) pins that fraction of VUs to the HOT tenant's sessions.
 */
export function pickSession(vu, roles, hotShare) {
  if (_mine) return _mine;
  const idx = sessionIndex();
  let pool = null;
  const h = ((vu * 40503) >>> 0) % 1000;
  if (hotShare > 0 && h < hotShare * 1000) {
    const hot = [];
    for (const r of roles) for (const i of (idx.hotByRole[r] || [])) hot.push(i);
    if (hot.length) pool = hot;
  }
  if (!pool) {
    pool = [];
    for (const r of roles) for (const i of (idx.byRole[r] || [])) pool.push(i);
  }
  if (!pool.length) return null;
  // SharedArray elements are READ-ONLY (a property assignment is silently dropped), so keep a plain
  // shallow copy per VU; nested arrays stay shared with the parsed element.
  _mine = Object.assign({}, sessionsArr[pool[(vu * 7919) % pool.length]], { runSeed: RUN_SEED });
  return _mine;
}

/** An owner session of a given tenant (for flows whose data row names the tenant). */
export function ownerSessionOf(tenantId) {
  const i = sessionIndex().ownerByTenant[tenantId];
  if (i === undefined) return null;
  return Object.assign({}, sessionsArr[i], { runSeed: RUN_SEED });
}

/** True when the session holds ANY of the listed permissions. */
export function canAny(session, ...perms) {
  const have = session.permissions || [];
  for (const p of perms) if (have.indexOf(p) !== -1) return true;
  return false;
}
