/**
 * Generates an authoritative SQL schema snapshot from the committed migrations.
 *
 * Why this exists: the project is migration-driven (synchronize=false) and has no
 * checked-in canonical schema file, so the only source of truth for the physical
 * schema is the 15 migrations. This script concatenates the DDL each migration's
 * `up()` actually runs — baseline tables plus every hardening object (exclusion
 * constraint, partial unique indexes, pgvector, triggers) — into docs/schema/schema.sql.
 *
 * It is a pure text extractor: it pulls the SQL out of every `queryRunner.query(`...`)`
 * call in the up() half of each migration (handles multi-line template literals).
 * It does NOT connect to a database. Re-run after adding migrations.
 */
const fs = require('node:fs');
const path = require('node:path');

const migrationsDir = path.join(__dirname, '..', 'src', 'migrations');
const outDir = path.join(__dirname, '..', 'docs', 'schema');
const outFile = path.join(outDir, 'schema.sql');

/** Extract every back-tick template literal passed to `.query(` before `async down`. */
function extractUpStatements(source) {
  const downIdx = source.indexOf('async down');
  const up = downIdx === -1 ? source : source.slice(0, downIdx);

  const statements = [];
  const marker = '.query(';
  let i = 0;
  while ((i = up.indexOf(marker, i)) !== -1) {
    // Find the opening backtick after `.query(`
    let j = i + marker.length;
    while (j < up.length && up[j] !== '`' && up[j] !== ')') j++;
    if (up[j] !== '`') { i = j; continue; }
    // Capture until the closing backtick (no ${} interpolation exists in this DDL).
    let k = j + 1;
    let buf = '';
    while (k < up.length && up[k] !== '`') { buf += up[k]; k++; }
    statements.push(buf.trim());
    i = k + 1;
  }
  return statements;
}

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.ts'))
  .sort(); // timestamp-prefixed → chronological order

let out = `-- ============================================================================\n`;
out += `--  AUTHORITATIVE PHYSICAL SCHEMA SNAPSHOT (generated)\n`;
out += `--  Source: src/migrations/* (up() DDL only), in execution order.\n`;
out += `--  Generated by scripts/extract-schema.js — DO NOT EDIT BY HAND.\n`;
out += `--  Regenerate: node scripts/extract-schema.js\n`;
out += `-- ============================================================================\n\n`;

let total = 0;
for (const file of files) {
  const src = fs.readFileSync(path.join(migrationsDir, file), 'utf8');
  const stmts = extractUpStatements(src);
  if (stmts.length === 0) continue;
  out += `\n-- ─────────────────────────────────────────────────────────────────────────\n`;
  out += `-- ${file}  (${stmts.length} statements)\n`;
  out += `-- ─────────────────────────────────────────────────────────────────────────\n\n`;
  for (const s of stmts) {
    out += s.endsWith(';') ? `${s}\n` : `${s};\n`;
    total += 1;
  }
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, out, 'utf8');
console.log(`Wrote ${outFile}`);
console.log(`Migrations processed: ${files.length}, total DDL statements: ${total}`);
